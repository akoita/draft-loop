#!/usr/bin/env node

// Regenerates packages/rendering/src/carlito-font-data.ts from the pinned upstream Carlito fonts.
//
//   node scripts/generate-carlito-font-module.mjs            download from the pinned commit
//   node scripts/generate-carlito-font-module.mjs --from DIR  read Carlito-*.ttf from DIR
//
// Each font is verified against its pinned SHA-256 before it is compressed, so a changed
// upstream file or a tampered download fails closed. The module stores the Flate-compressed
// font exactly as the PDF writer embeds it, plus the metrics read by the TrueType parser.

import { Buffer } from "node:buffer";
import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";
import { deflateSync } from "node:zlib";

import { parseTrueTypeFont } from "../packages/rendering/src/truetype-font.ts";
import { winAnsiCodePoint } from "../packages/rendering/src/winansi.ts";

export const carlitoSource = Object.freeze({
  repository: "https://github.com/google/fonts",
  commit: "3dd78844021e948ceb633d1dcee3f7885561b5d9",
  directory: "ofl/carlito",
  license: "SIL Open Font License 1.1",
  fonts: Object.freeze({
    "Carlito-Regular.ttf": {
      exportName: "carlitoRegular",
      baseFont: "Carlito",
      stemV: 80,
      sha256: "f6418f708baede9789daef5d458c0f53d2a888af9820e8062934e504fedc6595",
    },
    "Carlito-Bold.ttf": {
      exportName: "carlitoBold",
      baseFont: "Carlito-Bold",
      stemV: 150,
      sha256: "bb5d20f79b82599ec72983597437373a80f2d2085fa91fc144fd74e876a594db",
    },
  }),
});

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const outputPath = join(root, "packages/rendering/src/carlito-font-data.ts");

function sha256(bytes) {
  return createHash("sha256").update(bytes).digest("hex");
}

async function loadFont(fileName, directory) {
  if (directory !== undefined) return new Uint8Array(await readFile(join(directory, fileName)));
  const url = `https://raw.githubusercontent.com/google/fonts/${carlitoSource.commit}/${carlitoSource.directory}/${fileName}`;
  const response = await globalThis.fetch(url);
  if (!response.ok) throw new Error(`Could not download ${url}: HTTP ${response.status}`);
  return new Uint8Array(await response.arrayBuffer());
}

function embeddedFont(fileName, spec, bytes) {
  const actual = sha256(bytes);
  if (actual !== spec.sha256) {
    throw new Error(`${fileName} checksum ${actual} does not match the pinned ${spec.sha256}`);
  }
  const font = parseTrueTypeFont(bytes);
  const widths = [];
  for (let code = 32; code <= 255; code += 1) {
    widths.push(font.advanceWidth1000(winAnsiCodePoint(code)));
  }
  const { metrics } = font;
  const flate = deflateSync(bytes, { level: 9 });
  return `export const ${spec.exportName}: EmbeddedFontData = {
  baseFont: ${JSON.stringify(spec.baseFont)},
  sha256: ${JSON.stringify(spec.sha256)},
  length1: ${bytes.length},
  bbox: ${JSON.stringify(metrics.bbox)},
  ascent: ${metrics.ascent},
  descent: ${metrics.descent},
  capHeight: ${metrics.capHeight},
  italicAngle: ${metrics.italicAngle},
  stemV: ${spec.stemV},
  widths: ${JSON.stringify(widths)},
  flateBase64: ${JSON.stringify(Buffer.from(flate).toString("base64"))},
};
`;
}

async function main() {
  const fromIndex = process.argv.indexOf("--from");
  const directory = fromIndex === -1 ? undefined : resolve(process.argv[fromIndex + 1] ?? ".");
  const parts = [
    `// Generated by scripts/generate-carlito-font-module.mjs; do not edit by hand.
// Carlito (SIL Open Font License 1.1), unmodified, from ${carlitoSource.repository}
// at commit ${carlitoSource.commit} under ${carlitoSource.directory}/.
// Licence and notice: packages/rendering/fonts/carlito/.
import type { EmbeddedFontData } from "./truetype-font.js";
`,
  ];
  for (const [fileName, spec] of Object.entries(carlitoSource.fonts)) {
    parts.push(embeddedFont(fileName, spec, await loadFont(fileName, directory)));
  }
  await writeFile(outputPath, parts.join("\n"));
  process.stdout.write(`Wrote ${outputPath}\n`);
}

if (process.argv[1] !== undefined && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await main();
}
